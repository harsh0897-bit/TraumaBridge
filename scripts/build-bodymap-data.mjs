// Generate typescript and json files
function generateFiles(view, regions) {
  const jsonPath = path.resolve(`src/lib/bodymap/${view}.json`)
  fs.writeFileSync(jsonPath, JSON.stringify(regions, null, 2), 'utf8')

  const tsContent = `import type { BodyRegion, BodyViewData } from './types'
import ${view}Json from './${view}.json'

export const ${view.toUpperCase()}_REGIONS: BodyRegion[] = ${view}Json as unknown as BodyRegion[]

export const ${view.toUpperCase()}_VIEW: BodyViewData = {
  view: '${view}',
  imageWidth: 896,
  imageHeight: 1200,
  silhouette: [],
  regions: ${view.toUpperCase()}_REGIONS,
}
`
  const tsPath = path.resolve(`src/lib/bodymap/${view}.ts`)
  fs.writeFileSync(tsPath, tsContent, 'utf8')
  console.log(`Wrote ${tsPath} and ${jsonPath} with ${regions.length} regions.`)
}

